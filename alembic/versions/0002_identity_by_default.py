"""Allow Adminer to submit existing IDs while retaining automatic numbering."""
from alembic import op

revision = "0002"
down_revision = "0001"
branch_labels = None
depends_on = None


def upgrade():
    for table in ("users", "stars", "likes"):
        op.execute(f"ALTER TABLE {table} ALTER COLUMN id SET GENERATED BY DEFAULT")


def downgrade():
    for table in ("users", "stars", "likes"):
        op.execute(f"ALTER TABLE {table} ALTER COLUMN id SET GENERATED ALWAYS")
